"use strict";
const assert = require("assert");
const path = require("path");
const os = require("os");
const fs = require("fs");
const Module = require("module");
const vscode = {
  workspace: { getConfiguration: () => ({ get: (key) => key === "environmentSetting" ? "" : [], inspect: () => ({ globalValue: [] }) }) }
};
const load = Module._load;
Module._load = (request, parent, main) => request === "vscode" ? vscode : load(request, parent, main);
const api = require("./extension").__internals;
const { ensureSharedSessions } = require("./shared-sessions");
assert.strictEqual(api.normalizeHome("  C:\\Users\\x\\.codex\\ "), "C:\\Users\\x\\.codex");
assert.strictEqual(api.normalizeHome(""), "");
assert.strictEqual(api.samePath("C:\\X\\.codex", "c:\\x\\.CODEX"), process.platform === "win32");
assert.strictEqual(api.settingParts(), null);
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "codex-manager-"));
fs.writeFileSync(path.join(temp, "session.json"), "test");
assert.strictEqual(api.activity(temp).files, 1);
const shared = fs.mkdtempSync(path.join(os.tmpdir(), "codex-shared-"));
const profile = fs.mkdtempSync(path.join(os.tmpdir(), "codex-profile-"));
fs.mkdirSync(path.join(shared, "sessions"), { recursive: true });
fs.writeFileSync(path.join(shared, "sessions", "one.json"), "{}");
fs.writeFileSync(path.join(shared, "session_index.jsonl"), "{\"id\":\"one\"}\n");
ensureSharedSessions(shared, [profile]);
assert.strictEqual(fs.realpathSync(path.join(profile, "sessions")), fs.realpathSync(path.join(shared, "sessions")));
assert.strictEqual(fs.readFileSync(path.join(profile, "session_index.jsonl"), "utf8"), "{\"id\":\"one\"}\n");
ensureSharedSessions(shared, [profile]);
console.log("All Codex Account Manager tests passed.");
